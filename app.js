document.getElementById("exportContent").addEventListener("click", () => {
  syncAdminInputs();
  const blob = new Blob([JSON.stringify(content, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "anat-fanti-content.json";
  link.click();
  URL.revokeObjectURL(url);
});

document.getElementById("importContent").addEventListener("change", async (event) => {
  const file = event.target.files[0];
  if (!file) return;
  content = mergeContent(structuredClone(defaultContent), JSON.parse(await file.text()));
  localStorage.setItem(storageKey, JSON.stringify(content));
  renderAdmin();
  render();
});

document.getElementById("resetContent").addEventListener("click", () => {
  localStorage.removeItem(storageKey);
  content = structuredClone(defaultContent);
  renderAdmin();
  render();
});

