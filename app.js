document.getElementById("bookingForm").addEventListener("submit", (event) => {
  event.preventDefault();
  const form = new FormData(event.currentTarget);
  const subject = encodeURIComponent(`Booking inquiry from ${form.get("name")}`);
  const body = encodeURIComponent(
    `Name: ${form.get("name")}\nEmail: ${form.get("email")}\nEvent: ${form.get("event")}\n\n${form.get("message")}`
  );
  window.location.href = `mailto:${content.email}?subject=${subject}&body=${body}`;
});

