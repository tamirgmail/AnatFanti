document.getElementById("adminPanel").addEventListener("click", (event) => {
  const mediaIndex = event.target.dataset.removeMedia;
  const talkIndex = event.target.dataset.removeTalk;
  if (mediaIndex !== undefined) {
    syncAdminInputs();
    content[adminLang].media.splice(Number(mediaIndex), 1);
    renderAdmin();
  }
  if (talkIndex !== undefined) {
    syncAdminInputs();
    content[adminLang].talks.splice(Number(talkIndex), 1);
    renderAdmin();
  }
});

