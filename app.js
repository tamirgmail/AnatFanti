function loadContent() {
  const saved = localStorage.getItem(storageKey);
  if (!saved) return structuredClone(defaultContent);
  try {
    return mergeContent(structuredClone(defaultContent), JSON.parse(saved));
  } catch {
    return structuredClone(defaultContent);
  }
}

function mergeContent(base, incoming) {
  return {
    ...base,
    ...incoming,
    en: { ...base.en, ...(incoming.en || {}) },
    he: { ...base.he, ...(incoming.he || {}) }
  };
}

function render() {
  const data = content[currentLang];
  document.documentElement.lang = currentLang;
  document.body.dir = currentLang === "he" ? "rtl" : "ltr";
  document.body.dataset.theme = content.theme || "scholar";
  document.title = "Anat Fanti";
  document.querySelectorAll("[data-field]").forEach((element) => {
    const key = element.dataset.field;
    if (data[key]) element.textContent = data[key];
  });
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translations[currentLang][element.dataset.i18n] || element.textContent;
  });
  const langToggle = document.getElementById("langToggle");
  langToggle.textContent = currentLang === "en" ? "🇺🇸" : "🇮🇱";
  langToggle.setAttribute("aria-label", currentLang === "en" ? "English selected. Switch to Hebrew" : "Hebrew selected. Switch to English");
  document.getElementById("heroImage").src = content.heroImage;
  document.getElementById("emailLink").href = `mailto:${content.email}`;
  document.getElementById("emailLink").textContent = content.email;
  renderMedia();
  renderTalks();
  renderTemplates();
}

function renderMedia() {
  const grid = document.getElementById("mediaGrid");
  const items = content[currentLang].media.filter((item) => activeFilter === "all" || item.type === activeFilter);
  grid.innerHTML = items
    .map(
      (item) => {
        const embed = getEmbedHtml(item);
        return `
      <article class="media-card">
        <span class="media-type">${escapeHtml(item.type)}</span>
        <h3>${escapeHtml(item.title)}</h3>
        <p><strong>${escapeHtml(item.source)}</strong></p>
        ${embed}
        <p>${escapeHtml(item.description)}</p>
        <a href="${escapeAttribute(item.url)}" target="_blank" rel="noreferrer">${translations[currentLang].readMore}</a>
      </article>
    `;
      }
    )
    .join("");
}

function getEmbedHtml(item) {
  const youtubeId = getYouTubeId(item.url);
  if (youtubeId) {
    return `<iframe class="embed-frame" src="https://www.youtube.com/embed/${youtubeId}" title="${escapeAttribute(
      item.title
    )}" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe>`;
  }
  if (item.embedUrl) {
    return `<iframe class="embed-frame" src="${escapeAttribute(item.embedUrl)}" title="${escapeAttribute(
      item.title
    )}" allowfullscreen></iframe>`;
  }
  return item.type === "video" ? `<p class="admin-note">${translations[currentLang].unsupportedEmbed}</p>` : "";
}

function getYouTubeId(url) {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes("youtu.be")) return parsed.pathname.slice(1).split("/")[0];
    if (parsed.hostname.includes("youtube.com")) return parsed.searchParams.get("v");
  } catch {
    return null;
  }
  return null;
}

