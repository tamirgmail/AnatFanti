function syncAdminInputs() {
  document.querySelectorAll("[data-global-field]").forEach((input) => {
    content[input.dataset.globalField] = input.value;
  });
  document.querySelectorAll("[data-edit-field]").forEach((input) => {
    content[adminLang][input.dataset.editField] = input.value;
  });
  document.querySelectorAll("[data-media-index]").forEach((group) => {
    const index = Number(group.dataset.mediaIndex);
    group.querySelectorAll("[data-media-field]").forEach((input) => {
      content[adminLang].media[index][input.dataset.mediaField] = input.value;
    });
  });
  document.querySelectorAll("[data-talk-index]").forEach((group) => {
    const index = Number(group.dataset.talkIndex);
    group.querySelectorAll("[data-talk-field]").forEach((input) => {
      content[adminLang].talks[index][input.dataset.talkField] = input.value;
    });
  });
}

function openAdmin() {
  const dialog = document.getElementById("adminDialog");
  if (!dialog.open) dialog.showModal();
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeAttribute(value) {
  return escapeHtml(value).replaceAll("`", "&#096;");
}

